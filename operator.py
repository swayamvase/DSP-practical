a = 10
b = 5

# 1. Arithmetic Operators
print("Addition:", a + b)
print("Division:", a / b)

# 2. Relational (Comparison) Operators
print("a > b:", a > b)

# 3. Logical Operators
print("a > 5 and b < 10:", a > 5 and b < 10)

# 4. Bitwise Operators
print("a & b:", a & b)

# 5. Assignment Operators
a += b
print("Updated a:", a)

# 6. Membership Operators
list1 = [1, 2, 3, 4]
print("2 in list1:", 2 in list1)

# 7. Identity Operators
x = 10
y = 10
print("x is y:", x is y)